    private void capNhatKhiSuaSoLuongTrenBang(int row) {
        DefaultTableModel modelGH = (DefaultTableModel) tblGioHang.getModel();
        String maSP = modelGH.getValueAt(row, 0).toString();
        String slNhap = modelGH.getValueAt(row, 2).toString().trim();
        long donGia = Long.parseLong(modelGH.getValueAt(row, 3).toString().replaceAll("[^0-9]", ""));

        try {
            int slMoi = Integer.parseInt(slNhap);
            int tonKho = DonHangDao.laySoLuongTrenKe(maSP);

            if (slMoi <= 0) {
                // Nếu nhập số lượng <= 0 thì hỏi xóa sản phẩm khỏi giỏ hàng
                int chon = JOptionPane.showConfirmDialog(this, "Xóa sản phẩm này khỏi giỏ hàng?", "Xác nhận", JOptionPane.YES_NO_OPTION);
                if (chon == JOptionPane.YES_OPTION) {
                    modelGH.removeRow(row);
                    capNhatTongTien();
                    return;
                } else {
                    slMoi = 1;
                }
            } else if (slMoi > tonKho) {
                JOptionPane.showMessageDialog(this, "Số lượng vượt quá tồn kho! (Trong kho chỉ còn: " + tonKho + ")");
                slMoi = tonKho;
            }

            // Tính lại cột Tổng Tiền = SL mới * Đơn Giá
            long tongTien = slMoi * donGia;
            dangCapNhatBang = true;
            modelGH.setValueAt(slMoi, row, 2);
            modelGH.setValueAt(formatVND(tongTien), row, 4);
            dangCapNhatBang = false;

            // Tính lại Tổng Cộng và Thành Tiền bên phải
            capNhatTongTien();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Số lượng phải là số nguyên hợp lệ!");
            dangCapNhatBang = true;
            modelGH.setValueAt(1, row, 2);
            modelGH.setValueAt(formatVND(donGia), row, 4);
            dangCapNhatBang = false;
            capNhatTongTien();
        }
    }
    
    public void capNhatTongTien() {
        DefaultTableModel modelGH = (DefaultTableModel) tblGioHang.getModel();
        long tongCong = 0;

        //Cộng dồn cột Tổng Tiền của tất cả các dòng trong Giỏ hàng
        for (int i = 0; i < modelGH.getRowCount(); i++) {
            String chuoiTien = modelGH.getValueAt(i, 4).toString().replaceAll("[^0-9]", "");
            if (!chuoiTien.isEmpty()) {
                tongCong += Long.parseLong(chuoiTien);
            }
        }

        //Tính tiền Giảm Giá nếu đang áp dụng Voucher
        long tienGiam = 0;
        if (voucherDangApDung != null) {
            // Kiểm tra tổng tiền hiện tại còn đủ điều kiện của Voucher không
            boolean thoaManGiaTu = tongCong >= voucherDangApDung.getDieukienGiatu();
            boolean thoaManGiaDen = (voucherDangApDung.getDieukiengiaden() <= 0) || (tongCong <= voucherDangApDung.getDieukiengiaden());

            if (thoaManGiaTu && thoaManGiaDen) {
                tienGiam = Math.round(tongCong * (voucherDangApDung.getPhanTramGiam() / 100.0));
            } else {
                // Nếu xóa bớt hàng làm tổng tiền không còn đủ điều kiện Voucher -> Tự hủy Voucher
                voucherDangApDung = null;
                txtKhuyenMai.setText("");
                JOptionPane.showMessageDialog(this, "Tổng đơn hàng không còn nằm trong khoảng điều kiện của Voucher nên mã đã được gỡ!");
            }
        }

        //Tính Thành Tiền = Tổng cộng - Giảm giá
        long thanhTien = tongCong - tienGiam;
        if (thanhTien < 0) thanhTien = 0;

        lblTongCong.setText(formatVND(tongCong));
        lblGiamGia.setText(formatVND(tienGiam));
        lblThanhTien.setText(formatVND(thanhTien));
        tinhTienTraLaiKhach();
    }
    
    private void tinhTienTraLaiKhach() {
        String chuoiKhachTra = txtKhachTra.getText().replaceAll("[^0-9]", "");
        if (chuoiKhachTra.isEmpty()) {
            txtTraLaiKhach.setText("");
            return;
        }
        try {
            long khachTra = Long.parseLong(chuoiKhachTra);
            String chuoiThanhTien = lblThanhTien.getText().replaceAll("[^0-9]", "");
            long thanhTien = chuoiThanhTien.isEmpty() ? 0 : Long.parseLong(chuoiThanhTien);

            long tienThua = khachTra - thanhTien;
            if (tienThua >= 0) {
                txtTraLaiKhach.setText(formatVND(tienThua));
            } else {
                txtTraLaiKhach.setText("Thiếu " + formatVND(Math.abs(tienThua)));
            }
        } catch (NumberFormatException e) {
            txtTraLaiKhach.setText("0 đ");
        }
    }
    
    public void loadBangSanPham(String tuKhoa) {
        DefaultTableModel modelSP = (DefaultTableModel) tblSanPham.getModel();
        modelSP.setRowCount(0);

        // Nhận List<Object[]> từ DAO
        List<Object[]> ds = DonHangDao.getandsearchSanPhamDangBan(tuKhoa);

        for (Object[] row : ds) {
            // row[4] đang chứa GiaBan kiểu Long, ta format nó thành tiền tệ
            long giaBan = (Long) row[4]; 

            modelSP.addRow(new Object[]{
                row[0], // Mã SP
                row[1], // Tên SP
                row[2], // Loại SP
                row[3], // Số lượng
                formatVND(giaBan) // Giá bán đã format
            });
        }
    }
    
