    private void btnTaoPhieuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTaoPhieuActionPerformed
        // TODO add your handling code here:
        btnTaoPhieu.setVisible(false);
        btnHoanTat.setVisible(true);
        btnHuy.setVisible(true);

        cbbSanPham.setEnabled(true);
        txtSoLuongThem.setEnabled(true);
        txtGhiChu.setEnabled(true);
        btnThemSP.setEnabled(true);
        btnXoaSP.setEnabled(true);

        // Sinh mã tự động
        txtMaPhieu.setText(XuatHangDao.taoMaPhieuKeMoi());

        // Đổ dữ liệu vào ComboBox: Format (Mã SP) Tên SP
        cbbSanPham.removeAllItems();
        dsKho = XuatHangDao.layDanhSachSanPhamTrongKho();
        for (Object[] sp : dsKho) {
            cbbSanPham.addItem("(" + sp[0] + ") " + sp[1]);
        }
    }//GEN-LAST:event_btnTaoPhieuActionPerformed

    private void cbbSanPhamItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cbbSanPhamItemStateChanged
        // TODO add your handling code here:
        int index = cbbSanPham.getSelectedIndex();
        if (index >= 0 && dsKho != null) {
            // Lấy số lượng tồn kho từ mảng gốc (cột thứ 3) dựa theo index của ComboBox
            int tonKho = (Integer) dsKho.get(index)[2];
            lblTonKho.setText(String.valueOf(tonKho));
            
            double giaBan = (Double) dsKho.get(index)[3];
            txtGiaBan.setText(String.valueOf(giaBan));
        }
    }//GEN-LAST:event_cbbSanPhamItemStateChanged

    private void btnThemSPActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemSPActionPerformed
        // TODO add your handling code here:
        int index = cbbSanPham.getSelectedIndex();
        if (index < 0) return;
        
        String maSP = dsKho.get(index)[0].toString();
        String tenSP = dsKho.get(index)[1].toString();
        int tonKho = (Integer) dsKho.get(index)[2];
        
        try {
            int slThem = Integer.parseInt(txtSoLuongThem.getText().trim());
            double giaBan = Double.parseDouble(txtGiaBan.getText().trim());
            
            if (slThem <= 0 || slThem > tonKho) {
                JOptionPane.showMessageDialog(this, "Số lượng thêm không hợp lệ hoặc vượt quá tồn kho!");
                return;
            }
            
            DefaultTableModel model = (DefaultTableModel) tblDanhSachXuat.getModel();
            model.addRow(new Object[]{maSP, tenSP, slThem, giaBan});
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập số lượng và giá bán hợp lệ!");
        }
    }//GEN-LAST:event_btnThemSPActionPerformed

    private void btnHoanTatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHoanTatActionPerformed
        // TODO add your handling code here:
        if (tblDanhSachXuat.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "Danh sách xuất đang trống!");
        return;
    }
    
        boolean ok = XuatHangDao.luuPhieuXuatKe(txtMaPhieu.getText(), txtGhiChu.getText(), tblDanhSachXuat);
        if (ok) {
            JOptionPane.showMessageDialog(this, "Lưu phiếu xuất thành công!");
            this.dispose(); // Đóng cửa sổ popup
        } else {
            JOptionPane.showMessageDialog(this, "Lỗi khi lưu phiếu!");
        }
    }//GEN-LAST:event_btnHoanTatActionPerformed

    private void btnXoaSPActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaSPActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) tblDanhSachXuat.getModel();
        int selectedRow = tblDanhSachXuat.getSelectedRow(); // Lấy vị trí dòng đang được click chọn

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng click chọn một sản phẩm trong bảng phía dưới để xóa!");
            return;
        }

        // Hộp thoại xác nhận trước khi xóa cho chuyên nghiệp
        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn xóa sản phẩm này khỏi phiếu xuất?", "Xác nhận", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            model.removeRow(selectedRow); // Xóa dòng
        }
    }//GEN-LAST:event_btnXoaSPActionPerformed

    private void btnHuyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHuyActionPerformed
        // TODO add your handling code here:
        int confirm = JOptionPane.showConfirmDialog(this, "Hủy phiếu xuất này? Mọi dữ liệu đang nhập sẽ bị xóa sạch.", "Xác nhận hủy", JOptionPane.YES_NO_OPTION);
        
        if (confirm == JOptionPane.YES_OPTION) {
            // 1. Xóa sạch dữ liệu trong bảng danh sách xuất
            DefaultTableModel model = (DefaultTableModel) tblDanhSachXuat.getModel();
            model.setRowCount(0);

            // 2. Xóa trắng các ô chữ
            txtMaPhieu.setText("");
            txtSoLuongThem.setText("");
            txtGhiChu.setText("");
            lblTonKho.setText("0");
            cbbSanPham.removeAllItems();

            // 3. Khóa các thành phần và đổi lại nút bấm
            cbbSanPham.setEnabled(false);
            txtSoLuongThem.setEnabled(false);
            txtGhiChu.setEnabled(false);
            btnThemSP.setEnabled(false);
            btnXoaSP.setEnabled(false);
            
            btnTaoPhieu.setVisible(true);
            btnHoanTat.setVisible(false);
            btnHuy.setVisible(false);
            
            // Lưu ý: Nếu bạn muốn nút Hủy tắt luôn cửa sổ popup thay vì reset, 
            // bạn chỉ cần xóa toàn bộ code trên và dùng đúng 1 lệnh: this.dispose();
        }
    }//GEN-LAST:event_btnHuyActionPerformed

