    private void hienThiLenBangDanhSach(List<model.DonHang> ds) {
        DefaultTableModel modelDS = (DefaultTableModel) tblDanhSach.getModel();
        modelDS.setRowCount(0); // Xóa dữ liệu cũ

        // Xóa trắng bảng Chi tiết bên phải khi tải lại danh sách
        ((DefaultTableModel) tblChiTiet.getModel()).setRowCount(0);

        for (model.DonHang dh : ds) {
            String ngayLapStr = (dh.getNgayMua() != null) ? sdfNgayLap.format(dh.getNgayMua()) : "";
            String tongTienStr = formatVND(dh.getTongTien());
            String maGiamGia = (dh.getMaVoucher() != null) ? dh.getMaVoucher() : "Không có";

            modelDS.addRow(new Object[]{
                dh.getMaDH(),
                ngayLapStr,
                dh.getMaKH(),
                tongTienStr,
                maGiamGia
            });
        }
    }
    
    public void loadBangDanhSachHoaDon(String tuKhoa) {
        List<model.DonHang> ds = DonHangDao.layDanhSachDonHang(tuKhoa);
        hienThiLenBangDanhSach(ds);
    }

    // Hàm tải Chi tiết các món hàng của 1 hóa đơn lên bảng tblChiTiet (bên phải)
    public void loadBangChiTietHoaDon(String maHD) {
        DefaultTableModel modelCT = (DefaultTableModel) tblChiTiet.getModel();
        modelCT.setRowCount(0);

        List<ChiTietDonHang> dsCT = DonHangDao.layChiTietTheoMaDH(maHD);
        for (ChiTietDonHang ct : dsCT) {
            modelCT.addRow(new Object[]{
                ct.getMaSP(),
                ct.getTenSP(),
                formatVND(ct.getDonGia()),
                ct.getSoLuongMua(),
                formatVND(ct.getThanhTien())
            });
        }
    }
