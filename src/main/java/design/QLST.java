    private void setActiveButton(JButton selectedBtn) {
    if (currentActiveButton != null) {
        currentActiveButton.setContentAreaFilled(false); 
        currentActiveButton.setFont(new Font("Segoe UI", Font.BOLD, 18)); 
        currentActiveButton.setForeground(Color.WHITE);
    }
    
    selectedBtn.setBackground(new Color(0, 120, 120));
    selectedBtn.setFont(new Font("Segoe UI", Font.BOLD, 18));  
    selectedBtn.setForeground(Color.YELLOW); 

    // 3. Cập nhật nút hiện tại
    currentActiveButton = selectedBtn;
}
    
