    private void initCustomThongKe() {
        chart = new Chart();
   chartPanel.setLayout(new java.awt.BorderLayout());
    chartPanel.add(chart, java.awt.BorderLayout.CENTER);
        chartPanel.revalidate();
        chartPanel.repaint();
        LocalDate today = LocalDate.now();
        LocalDate currentMonday = today.with(DayOfWeek.MONDAY);

        weekMondays.clear();
        jComboBox1.removeAllItems();

        isUpdatingCombo = true;
        for (int i = 0; i < 12; i++) {
            LocalDate mon = currentMonday.minusWeeks(i);
            LocalDate sun = mon.plusDays(6);
            weekMondays.add(mon);

            String label;
            if (i == 0) {
                label = "Tuần này (" + mon.format(dtfWeek) + " - " + sun.format(dtfWeek) + ")";
            } else if (i == 1) {
                label = "Tuần trước (" + mon.format(dtfWeek) + " - " + sun.format(dtfWeek) + ")";
            } else {
                label = "Tuần " + mon.format(dtfWeek) + " - " + sun.format(dtfWeek);
            }
            jComboBox1.addItem(label);
        }
        isUpdatingCombo = false;

        // Chọn mặc định tuần hiện tại và tải dữ liệu
        if (jComboBox1.getItemCount() > 0) {
            jComboBox1.setSelectedIndex(0);
        }
    }

    private void loadDataAsync(LocalDate monday) {
      

        LocalDate nextMonday = monday.plusDays(7);

        // Danh sách 7 ngày trong tuần từ Thứ 2 đến Chủ nhật
        ArrayList<LocalDate> days = new ArrayList<>();
        for (int i = 0; i < 7; i++) {
            days.add(monday.plusDays(i));
        }
                Map<String, String> cats = ThongKeDao.layDanhSachLoaiSanPham();
                ArrayList<ThongKeLoaiSPNgay> sales = ThongKeDao.layThongKeSoLuongTheoLoaiVaNgay(monday, nextMonday);
                SanPhamBanChay best = ThongKeDao.laySanPhamBanChayNhat(monday, nextMonday);
                double rev = ThongKeDao.layTongDoanhThuTuan(monday, nextMonday);
                 KetQuaThongKe res=new KetQuaThongKe(cats, sales, best, rev);
 
    try {
      
        chart.setData(days, res.getCategories(), res.getSalesData());
        chart.revalidate();
        chart.repaint();

        TotalLB.setText(String.format("%,.0f đ", res.getTotalRevenue()));
        TotalLB.setToolTipText(String.format("%,.0f VNĐ", res.getTotalRevenue()));

        if (res.getBestSellers() == null ) {
            MaLB.setText("---");
            TenLB.setText("---");
            TenLB.setToolTipText(null);
            LSPLB.setText("---");
        } else {
            SanPhamBanChay sp = res.getBestSellers();
           
                MaLB.setText(sp.getMaSP());
                TenLB.setText(sp.getTenSP() + " (" + sp.getTongSoLuongBan() + " " + sp.getDonViTinh() + ")");
            
            TenLB.setToolTipText(sp.getTenSP() + " - Đã bán: " + sp.getTongSoLuongBan() + " " + sp.getDonViTinh());
            LSPLB.setText(sp.getLoaiSP());
        }
    } catch (Exception ex) {
        ex.printStackTrace();
        TotalLB.setText("0 đ");
        TenLB.setText("Lỗi kết nối CSDL");
    }
}

   
